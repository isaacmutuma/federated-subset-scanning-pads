N_BINS     = int(os.environ.get('N_BINS', 10))   # NOTE: select on validation, not test
ALPHA      = 1.0     # Laplace (add-one) smoothing
A_MAX      = 0.5
RESTARTS   = 5
BACKGROUND = os.environ.get('BACKGROUND', 'val_hc')  # 'val_hc' (held-out) or 'hc_train' (original)
EVAL_TASK  = os.environ.get('EVAL_TASK') or None     # e.g. 'relaxed' — substring match; None = all
EVAL_WRIST = os.environ.get('EVAL_WRIST') or None    # e.g. 'right'   — substring match; None = both
RUN_TAG    = os.environ.get('RUN_TAG', '')           # suffix for result files of variant runs

LAYERS_TO_SCAN = ['layer_0', 'layer_1', 'layer_2']

try:
    GIT_COMMIT = subprocess.check_output(['git', '-C', C.REPO_DIR, 'rev-parse', 'HEAD'],
                                         text=True).strip()
except Exception:
    GIT_COMMIT = 'unknown'
RUN_CONFIG = {'n_bins': N_BINS, 'alpha': ALPHA, 'a_max': A_MAX, 'restarts': RESTARTS,
              'background': BACKGROUND, 'edges_from': 'hc_train', 'direction_source': 'val_pd vs hc_train',
              'eval_task': EVAL_TASK, 'eval_wrist': EVAL_WRIST, 'run_tag': RUN_TAG,
              'git_commit': GIT_COMMIT}
print(f"Run config: {RUN_CONFIG}")


def act_path(k, name):
    return osp.join(ACT_DIR, f'activations_fold{k}_{name}.npy')


def eval_mask(k, split, n):
    """Window mask selecting EVAL_TASK / EVAL_WRIST, using saved per-window metadata."""
    mask = np.ones(n, dtype=bool)
    for value, field in [(EVAL_TASK, 'task'), (EVAL_WRIST, 'wrist')]:
        if value is None:
            continue
        path = act_path(k, f'{split}_{field}')
        assert osp.exists(path), f"{path} missing — re-run extract_activations.py"
        meta = np.char.lower(np.load(path).astype(str))
        mask &= np.char.find(meta, value.lower()) >= 0
    assert mask.any(), f"No {split} windows match task={EVAL_TASK} wrist={EVAL_WRIST}"
    return mask


# ── FGSS wrappers: real failures are counted, not silently scored as normal ───
# fgss_individ_for_nets expects pvalues of shape (n_nodes, 2) = [pmin, pmax] per node
# and reads pmax from column 1. (Earlier versions passed shape (1, n_nodes), so only
# node 1's p-value was scanned.) A window with no p-value <= a_max has no candidate
# subset: ART raises on the empty search, but the correct scan score is 0
# ("nothing anomalous"), so it is scored 0 and counted separately from genuine errors.
FGSS_FAILURES = {'individ': 0, 'group': 0, 'individ_empty_subset': 0}

def safe_individ_score(pvals_1d, a_max=A_MAX, score_fn=None):
    if pvals_1d.min() > a_max:
        FGSS_FAILURES['individ_empty_subset'] += 1
        return 0.0
    try:
        score, _, _, _ = Scanner.fgss_individ_for_nets(
            pvalues=np.stack([pvals_1d, pvals_1d], axis=1).astype(np.float64),
            a_max=a_max, score_function=score_fn)
        return float(score)
    except Exception:
        FGSS_FAILURES['individ'] += 1
        return np.nan


def safe_group_score(p_subj_2d, a_max=A_MAX, restarts=RESTARTS, score_fn=None):
    try:
        p_3d = np.stack([p_subj_2d, p_subj_2d], axis=2).astype(np.float64)
        best_score, image_sub, node_sub, _ = Scanner.fgss_for_nets(
            pvalues=p_3d, a_max=a_max, restarts=restarts, score_function=score_fn)
        return float(best_score), len(image_sub), len(node_sub)
    except Exception:
        FGSS_FAILURES['group'] += 1
        return np.nan, 0, 0


def subject_scores(p_matrix, subj, method, score_fn=None):
    """Subject-level anomaly scores for one method. Returns (unique_subj, scores)."""
    unique_subj = np.unique(subj)
    if method == 'mean':
        win = 1.0 - p_matrix.mean(axis=1)
        return unique_subj, np.array([win[subj == s].mean() for s in unique_subj])
    if method == 'individ':
        win = np.array([safe_individ_score(p, score_fn=score_fn) for p in p_matrix])
        return unique_subj, np.array([np.nanmean(win[subj == s]) for s in unique_subj])
    if method == 'group':
        return unique_subj, np.array([safe_group_score(p_matrix[subj == s], score_fn=score_fn)[0]
                                      for s in unique_subj])
    raise ValueError(method)


def fold_metrics(y, scores):
    keep = ~np.isnan(scores)
    m = compute_metrics(y[keep], scores[keep])
    m['spec_at_90sens'] = spec_at_sens(y[keep], scores[keep], 0.9)
    m['n_failed_subjects'] = int((~keep).sum())
    return m


# ── Run DeepScan per layer ────────────────────────────────────────────────────
METHODS = ['mean', 'individ', 'group'] if ART_AVAILABLE else ['mean']
METHOD_LABELS = {'mean': 'A) Mean p-value', 'individ': 'B) Per-window FGSS',
                 'group': 'C) Group FGSS'}
all_results = {}

for layer in LAYERS_TO_SCAN:
    print(f"\n{'#'*60}")
    print(f"LAYER: {layer.upper()}")
    print(f"{'#'*60}")

    RESULTS_FILE = osp.join(C.RESULTS_DIR, f'deepscan_results_{layer}{RUN_TAG}.json')
    per_fold = {m: [] for m in METHODS}
    dd_per_fold = []
    # Pooled subject scores across folds, for bootstrap CIs / paired tests
    pooled = {'subj': [], 'label': [], 'fold': [], **{m: [] for m in METHODS}}
    score_fn = ScoringFunctions.get_score_bj_fast if ART_AVAILABLE else None

    for fold_idx in range(C.N_SPLITS):
        k = fold_idx + 1
        print(f"\n{'='*55}\nFOLD {k}/{C.N_SPLITS}\n{'='*55}")

        hc_train  = np.load(act_path(k, f'{layer}_hc_train'))
        bg_acts   = np.load(act_path(k, f'{layer}_{BACKGROUND}'))
        val_pd    = np.load(act_path(k, f'{layer}_val_pd'))
        test_acts = np.load(act_path(k, f'{layer}_test'))
        test_lab  = np.load(act_path(k, 'test_labels'))
        test_subj = np.load(act_path(k, 'test_subj'))

        m_test = eval_mask(k, 'test', len(test_acts))
        test_acts, test_lab, test_subj = test_acts[m_test], test_lab[m_test], test_subj[m_test]
        # Reference must describe the same task/wrist as the windows being scored
        hc_train = hc_train[eval_mask(k, 'hc_train', len(hc_train))]
        bg_acts  = bg_acts[eval_mask(k, BACKGROUND, len(bg_acts))]
        val_pd   = val_pd[eval_mask(k, 'val_pd', len(val_pd))]

        print(f"HC train (edges): {hc_train.shape}  Background ({BACKGROUND}): {bg_acts.shape}  "
              f"Val PD: {val_pd.shape}")
        print(f"Test: {test_acts.shape}  HC={(test_lab==0).sum()}  PD={(test_lab==1).sum()}")

        # Central (server) quantities: shared edges + tail direction
        edges = make_global_edges(hc_train, N_BINS)
        direction_mask = val_pd.mean(0) > hc_train.mean(0)
        print(f"Direction: {direction_mask.sum()} upper  {(~direction_mask).sum()} lower")

        # HC reference = counts of background under the shared edges
        ref_counts = site_counts(bg_acts, edges)
        p_matrix = pvalues_from_counts(ref_counts, edges, test_acts, direction_mask, ALPHA)
        print(f"  HC p mean: {p_matrix[test_lab==0].mean():.4f}  "
              f"PD p mean: {p_matrix[test_lab==1].mean():.4f}")

        unique_subj = np.unique(test_subj)
        subj_true   = np.array([test_lab[test_subj==s][0] for s in unique_subj])
        pooled['subj'].extend(unique_subj.tolist())
        pooled['label'].extend(subj_true.tolist())
        pooled['fold'].extend([k] * len(unique_subj))

        fold_scores = {}
        for method in METHODS:
            _, scores = subject_scores(p_matrix, test_subj, method, score_fn)
            fold_scores[method] = scores
            pooled[method].extend(scores.tolist())
            m = fold_metrics(subj_true, scores)
            per_fold[method].append(m)
            print(f"{METHOD_LABELS[method]} — ", end=""); print_fold_results(fold_idx, m)

        # DD subjects: scored with Method A against the same reference
        dd_path = act_path(k, f'{layer}_dd')
        if osp.exists(dd_path):
            dd_acts = np.load(dd_path)
            dd_subj = np.load(act_path(k, 'dd_subj'))
            m_dd = eval_mask(k, 'dd', len(dd_acts))
            p_dd = pvalues_from_counts(ref_counts, edges, dd_acts[m_dd], direction_mask, ALPHA)
            _, dd_scores = subject_scores(p_dd, dd_subj[m_dd], 'mean')
            hc_scores = fold_scores['mean'][subj_true == 0]
            pd_scores = fold_scores['mean'][subj_true == 1]
            y_hc_dd = np.r_[np.zeros(len(hc_scores)), np.ones(len(dd_scores))]
            y_hc_any = np.r_[np.zeros(len(hc_scores)), np.ones(len(pd_scores) + len(dd_scores))]
            dd_m = {'auc_hc_vs_dd': fold_metrics(y_hc_dd, np.r_[hc_scores, dd_scores])['auc'],
                    'auc_hc_vs_pd_dd': fold_metrics(
                        y_hc_any, np.r_[hc_scores, pd_scores, dd_scores])['auc'],
                    'n_dd_subjects': int(len(dd_scores))}
            dd_per_fold.append(dd_m)
            print(f"DD (Method A) — HC vs DD AUC: {dd_m['auc_hc_vs_dd']:.4f}  "
                  f"HC vs PD+DD AUC: {dd_m['auc_hc_vs_pd_dd']:.4f}")

        with open(RESULTS_FILE, 'w') as f:
            json.dump({'layer': layer, 'config': RUN_CONFIG, 'folds_complete': k,
                       'fold_metrics': per_fold, 'dd_fold_metrics': dd_per_fold}, f, indent=2)

    # Summary for this layer
    print(f"\n{'='*55}")
    print(f"LAYER {layer.upper()} — SUMMARY")
    print(f"{'='*55}")
    y_pool = np.array(pooled['label'])
    layer_result = {'config': RUN_CONFIG, 'fgss_failures': dict(FGSS_FAILURES),
                    'fold_metrics': per_fold, 'dd_fold_metrics': dd_per_fold,
                    'subject_scores': pooled}
    for method in METHODS:
        print(f"\n{METHOD_LABELS[method]}")
        agg = aggregate_fold_metrics(per_fold[method])
        agg['spec_at_90sens_mean'] = round(float(np.mean(
            [m['spec_at_90sens'] for m in per_fold[method]])), 4)
        s = np.array(pooled[method])
        keep = ~np.isnan(s)
        # Pooled across folds: Method A scores share a scale; FGSS scores may not
        agg['pooled_bootstrap'] = bootstrap_auc_ci(y_pool[keep], s[keep])
        print_summary(agg)
        print(f"Spec @ 90% sens:   {agg['spec_at_90sens_mean']:.4f}")
        print(f"Pooled AUC 95% CI: {agg['pooled_bootstrap']}")
        layer_result[f'aggregate_{method}'] = agg
    if 'group' in METHODS:
        a, c = np.array(pooled['mean']), np.array(pooled['group'])
        keep = ~(np.isnan(a) | np.isnan(c))
        layer_result['paired_A_vs_C'] = paired_bootstrap_auc_diff(y_pool[keep], a[keep], c[keep])
        print(f"\nPaired A vs C (pooled): {layer_result['paired_A_vs_C']}")
    if dd_per_fold:
        layer_result['aggregate_dd'] = {
            key: [round(float(np.mean([d[key] for d in dd_per_fold])), 4),
                  round(float(np.std([d[key] for d in dd_per_fold])), 4)]
            for key in ['auc_hc_vs_dd', 'auc_hc_vs_pd_dd']}
        print(f"DD summary (mean, std): {layer_result['aggregate_dd']}")
    print(f"FGSS failures so far: {FGSS_FAILURES}")

    all_results[layer] = layer_result
    with open(RESULTS_FILE, 'w') as f:
        json.dump({'layer': layer, 'evaluation': 'subject-level mean pooling',
                   **layer_result}, f, indent=2)

# ── Final comparison table ────────────────────────────────────────────────────
print(f"\n{'#'*60}")
print("FINAL COMPARISON — " + " vs ".join(LAYERS_TO_SCAN))
print(f"{'#'*60}")
print(f"{'Method':<30}" + "".join(f"{l:>18}" for l in LAYERS_TO_SCAN))
print("-"*(30 + 18 * len(LAYERS_TO_SCAN)))
for method in METHODS:
    row = f"{METHOD_LABELS[method]:<30}"
    for l in LAYERS_TO_SCAN:
        agg = all_results[l][f'aggregate_{method}']
        row += f"   {agg['auc_mean']:.4f} ± {agg['auc_std']:.3f}"
    print(row)

with open(osp.join(C.RESULTS_DIR, f'deepscan_comparison{RUN_TAG}.json'), 'w') as f:
    json.dump({l: {k: v for k, v in r.items() if k != 'subject_scores'}
               for l, r in all_results.items()}, f, indent=2)

print(f"\nResults saved to: {C.RESULTS_DIR}")
print("DONE.")
