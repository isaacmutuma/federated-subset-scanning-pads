"""
run_deepscan.py
---------------
Phase 4: Histogram-based subset scanning on PatchTST activations.

Runs DeepScan for each layer in LAYERS_TO_SCAN and compares results.
Activation files must be generated by extract_activations.py first.

Federated-compatible reference (src/scanning/histograms.py):
  - Bin edges are fixed once from server-side HC train activations (open-ended outer bins).
  - The HC reference is the COUNT matrix of BACKGROUND activations under those shared edges.
    BACKGROUND='val_hc' (default) uses HC subjects the encoder never trained on;
    'hc_train' reproduces the original (leaky) setup.
  - Tail direction per neuron is set centrally from val PD vs HC train.

Three scoring methods per layer:
  A) Simple mean p-value
  B) Per-window FGSS (fgss_individ_for_nets)
  C) Group FGSS per subject (fgss_for_nets — SubsetGAN approach)
     pvalues shape: (n_windows, n_neurons, 2)

If DD activations exist, DD subjects are also scored (HC vs DD, HC vs PD+DD).

Run:
    python scripts/run_deepscan.py
"""

